#!/usr/bin/env python3
"""Extract the Win16 cursors embedded in ABC.EXE and emit src/cursors_data.h.

The resource names come from the original executable (PEDZEL and the LIT_*
maze cursors). `wrestool` (icoutils) is used to pull the raw group and cursor
resources; the .cur DIB is then split into the 1-bpp SDL data/mask bitmaps.

Usage: tools/extract_cursors.py path/to/ABC.EXE
"""
import os
import struct
import subprocess
import sys
import tempfile

NAMES = [
    "PEDZEL",
    "LIT_C", "LIT_D", "LIT_F", "LIT_G", "LIT_I", "LIT_K",
    "LIT_L", "LIT_M", "LIT_O", "LIT_P", "LIT_U", "LIT_W",
]


def wrestool_raw(exe, rtype, name, out):
    cmd = ["wrestool", "--raw", "-x", "-t", str(rtype), "-n", str(name), "-o", out, exe]
    r = subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if r.returncode != 0 or not os.path.exists(out):
        raise RuntimeError(f"cannot extract type {rtype} name {name}")
    return open(out, "rb").read()


def cursor_bits(raw):
    """Return (w, h, hotx, hoty, data[128], mask[128]) for a 32x32 1-bpp cursor."""
    hotx, hoty = struct.unpack_from("<HH", raw, 0)
    bi_size = struct.unpack_from("<I", raw, 4)[0]
    w = struct.unpack_from("<i", raw, 8)[0]
    h2 = struct.unpack_from("<i", raw, 12)[0]
    planes, bpp = struct.unpack_from("<HH", raw, 16)
    if bpp != 1:
        raise RuntimeError(f"unsupported cursor bpp {bpp}")
    h = abs(h2) // 2
    palette = 2 * 4
    off = 4 + bi_size + palette
    stride = ((w + 31) // 32) * 4
    rows = [raw[off + y * stride: off + (y + 1) * stride] for y in range(h * 2)]
    # The first block is the image (XOR), the second the AND mask; both are
    # bottom-up.  SDL wants top-down, MSB-first rows; its mask bit 1 = opaque,
    # while the Win16 AND bit 1 = transparent.
    xor_rows = rows[:h]
    and_rows = rows[h:]
    data = bytearray()
    mask = bytearray()
    for y in range(h):
        data += xor_rows[h - 1 - y]
        src = and_rows[h - 1 - y]
        inv = bytes((~b) & 0xFF for b in src)
        mask += inv
    return w, h, hotx, hoty, bytes(data), bytes(mask)


def c_array(blob):
    lines = []
    for i in range(0, len(blob), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 12]) + ",")
    return "\n".join(lines)


def main():
    exe = sys.argv[1] if len(sys.argv) > 1 else "../abc-re/abc/ABC.EXE"
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = os.path.join(here, "src", "cursors_data.h")
    entries = []
    with tempfile.TemporaryDirectory() as td:
        for name in NAMES:
            grp = wrestool_raw(exe, 12, name, os.path.join(td, "g.bin"))
            # GRPCURSOR: reserved, type, count, then a 14-byte entry; id at +18.
            cid = struct.unpack_from("<H", grp, 18)[0]
            raw = wrestool_raw(exe, 1, cid, os.path.join(td, "c.bin"))
            w, h, hx, hy, data, mask = cursor_bits(raw)
            entries.append((name, w, h, hx, hy, data, mask))
            print(f"{name}: id={cid} {w}x{h} hot=({hx},{hy})")

    with open(out_path, "w") as f:
        f.write("/* Generated by tools/extract_cursors.py from ABC.EXE. */\n")
        f.write("#ifndef ABC_CURSORS_DATA_H\n#define ABC_CURSORS_DATA_H\n\n")
        f.write("typedef struct AbcCursorDef {\n"
                "    const char *name;\n"
                "    int w, h, hot_x, hot_y;\n"
                "    const unsigned char *data;\n"
                "    const unsigned char *mask;\n"
                "} AbcCursorDef;\n\n")
        for name, w, h, hx, hy, data, mask in entries:
            f.write(f"static const unsigned char cur_{name}_data[] = {{\n{c_array(data)}\n}};\n")
            f.write(f"static const unsigned char cur_{name}_mask[] = {{\n{c_array(mask)}\n}};\n\n")
        f.write("static const AbcCursorDef abc_cursors[] = {\n")
        for name, w, h, hx, hy, data, mask in entries:
            f.write(f'    {{"{name}", {w}, {h}, {hx}, {hy}, cur_{name}_data, cur_{name}_mask}},\n')
        f.write("};\n")
        f.write(f"static const int abc_cursor_count = {len(entries)};\n\n")
        f.write("#endif\n")
    print("wrote", out_path)


if __name__ == "__main__":
    main()
